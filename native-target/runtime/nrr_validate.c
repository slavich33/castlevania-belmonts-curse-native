static uint32_t nrr_u32(const uint8_t *p) {
    return (uint32_t)p[0]|(uint32_t)p[1]<<8|(uint32_t)p[2]<<16|(uint32_t)p[3]<<24;
}
static uint64_t nrr_u64(const uint8_t *p) {return nrr_u32(p)|(uint64_t)nrr_u32(p+4)<<32;}
static int nrr_verify_pss(const uint8_t modulus[256],const uint8_t signature[256],
                          const uint8_t *message,size_t size) {
    /* PKCS#1 RSAPublicKey DER, unsigned 2048-bit modulus and exponent65537. */
    if(!(modulus[0]&0x80)||!(modulus[255]&1))return 0;
    uint8_t der[270]={0x30,0x82,0x01,0x0a,0x02,0x82,0x01,0x01,0x00};
    memcpy(der+9,modulus,256);const uint8_t exponent[]={2,3,1,0,1};memcpy(der+265,exponent,5);
    CFDataRef encoded=CFDataCreate(kCFAllocatorDefault,der,sizeof der);
    const void *keys[]={kSecAttrKeyType,kSecAttrKeyClass};
    const void *values[]={kSecAttrKeyTypeRSA,kSecAttrKeyClassPublic};
    CFDictionaryRef attributes=CFDictionaryCreate(kCFAllocatorDefault,keys,values,2,
                                                 &kCFTypeDictionaryKeyCallBacks,&kCFTypeDictionaryValueCallBacks);
    SecKeyRef key=encoded&&attributes?SecKeyCreateWithData(encoded,attributes,NULL):NULL;
    CFDataRef data=CFDataCreate(kCFAllocatorDefault,message,(CFIndex)size);
    CFDataRef sig=CFDataCreate(kCFAllocatorDefault,signature,256);
    int valid=key&&data&&sig&&SecKeyIsAlgorithmSupported(key,kSecKeyOperationTypeVerify,
                                                       kSecKeyAlgorithmRSASignatureMessagePSSSHA256)&&
        SecKeyVerifySignature(key,kSecKeyAlgorithmRSASignatureMessagePSSSHA256,data,sig,NULL);
    if(sig)CFRelease(sig);if(data)CFRelease(data);if(key)CFRelease(key);
    if(attributes)CFRelease(attributes);if(encoded)CFRelease(encoded);return valid;
}
/* Internal core permits independently signed native test fixtures. It is not
 * exported, exposed through configuration or called by the IPC adapter directly. */
static const char *nrr_validate_with_modulus(const uint8_t *b,size_t size,uint64_t program_id,
                                            const uint8_t root[256],RuntimeNrrValidated *out) {
    if(!b||!root||!out)return "NRR validation arguments";
    if(size<0x350||size>RUNTIME_NRR_MAX_BYTES||(size&0xfff))return "NRR snapshot size";
    if(memcmp(b,"NRR0",4))return "NRR magic";
    if(nrr_u32(b+4)>=2)return "NRR unsupported production key generation";
    if(nrr_u32(b+0x338)!=size)return "NRR declared size";
    if(nrr_u64(b+0x330)!=program_id)return "NRR program identity";
    if((program_id&nrr_u64(b+0x10))!=nrr_u64(b+0x18))return "NRR certificate program mask";
    if(b[0x33c]!=0)return "NRR unsupported kind (User required)";
    uint32_t offset=nrr_u32(b+0x340),count=nrr_u32(b+0x344);
    if(offset<0x350||offset>size||count>(size-offset)/32)return "NRR hash table bounds";
    for(uint32_t i=1;i<count;i++)if(memcmp(b+offset+(size_t)(i-1)*32,b+offset+(size_t)i*32,32)>=0)
        return "NRR hashes must be sorted and unique";
    if(!nrr_verify_pss(root,b+0x130,b+0x10,0x120))return "NRR certificate signature";
    if(!nrr_verify_pss(b+0x30,b+0x230,b+0x330,size-0x330))return "NRR signature";
    RuntimeNrrValidated result={.hashes_offset=offset,.hash_count=count,.key_generation=nrr_u32(b+4)};
    CC_SHA256(b+0x330,(CC_LONG)(size-0x330),result.signed_area_sha256);*out=result;return NULL;
}
const char *runtime_nrr_validate(const uint8_t *snapshot,size_t size,uint64_t program_id,
                                 RuntimeNrrValidated *out) {
    if(!snapshot||size<8)return "NRR validation header missing";
    uint32_t generation=nrr_u32(snapshot+4);
    if(generation>=2)return "NRR unsupported production key generation";
    return nrr_validate_with_modulus(snapshot,size,program_id,nrr_production_moduli[generation],out);
}
